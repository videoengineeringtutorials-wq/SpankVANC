"""Validate decoded A/53 transport bytes against the exact generated journal.

Compile tests/inspect_a53.c against an independent FFmpeg decoder first.
This checks 29.97/30 fps output (SDI's CDP builder is checked natively).
"""
import argparse
import json
from pathlib import Path
import subprocess


def inspect(inspector,path,journal,strip=False):
    p=subprocess.run([str(inspector),str(path)],capture_output=True,text=True,check=True)
    frames=[bytes.fromhex(line.partition(' ')[2]) for line in p.stdout.splitlines()]
    assert frames, 'No decoded video frames'
    received=bytearray()
    for number,data in enumerate(frames):
        if strip:
            assert not data, f'{path}: strip frame {number} still has captions'
            continue
        assert len(data)==60, f'{path}: frame {number} has {len(data)//3} tuples, expected 20'
        assert data[0]==0xfc and data[3:6]==b'\xf9\x80\x80', f'{path}: bad field slots at {number}'
        assert all(v.bit_count()%2==1 for v in data[1:3]),f'{path}: parity at {number}'
        assert data[6:]==b'\xfa\x00\x00'*18,f'{path}: invalid padding at {number}'
        if data[1:3]!=b'\x80\x80':received.extend(data[1:3])
    if not strip:
        assert received==journal, f'{path}: generated bytes lost, reordered or duplicated ({len(received)} / {len(journal)})'
    return {'frames':len(frames),'continuous_20_tuple_payload':not strip,'journal_pairs_preserved':len(received)//2,'strip':strip}


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--inspector',type=Path,required=True);p.add_argument('--journal',type=Path,required=True)
    p.add_argument('--input',type=Path,action='append',default=[]);p.add_argument('--strip',type=Path,action='append',default=[])
    p.add_argument('--report',type=Path)
    args=p.parse_args();journal=args.journal.read_bytes()
    report={str(path.name):inspect(args.inspector,path,journal,False) for path in args.input}
    report.update({str(path.name):inspect(args.inspector,path,journal,True) for path in args.strip})
    if args.report:args.report.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))


if __name__=='__main__':main()
